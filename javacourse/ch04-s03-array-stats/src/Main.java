public class Main {
    public static void main(String[] args) {
        // 本板块 TODO（做完一条就删掉一条对应注释）：
        // - 用 (double) sum / arr.length 计算并打印平均分，保留小数
        // - 用打擂台法求最高分（max 初值取 arr[0]），并记录最高分的下标，打印成最高分在第几位
        // - 用同样的擂台法求出最低分并打印

        int[] arr = {88, 92, 56, 77, 100};

        // 求和：循环前准备累加器，循环中不断累加
        int sum = 0;
        for (int i = 0; i < arr.length; i++) {
            sum += arr[i];
        }
        System.out.println("总分：" + sum);
    }
}
