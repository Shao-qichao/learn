public class Main {
    public static void main(String[] args) {
        // 本板块 TODO（做完一条就删掉一条对应注释）：
        // - 把 target 改成 66，观察 index 仍然是 -1，并补上 if-else：找到打印找到了下标，没找到打印没找到
        // - 给数组 {5, 3, 8, 1} 手写冒泡排序，相邻两个比较、大的往右换，排成升序
        // - 用普通 for 循环把排序后的数组依次打印出来

        int[] arr = {88, 92, 56, 77, 100};
        int target = 56;
        int index = -1;   // -1 表示没找到

        for (int i = 0; i < arr.length; i++) {
            if (arr[i] == target) {
                index = i;
                break;
            }
        }
        System.out.println("下标：" + index);
    }
}
